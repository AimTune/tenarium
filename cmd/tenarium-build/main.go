// Command tenarium-build compiles a custom Tenarium binary with extra
// plugins, like xcaddy does for Caddy:
//
//	tenarium-build --with github.com/acme/tenarium-billing@v1.2.0 -o ./tenarium
//	tenarium-build --with example.com/myplugin=../myplugin   # local checkout
//	tenarium-build --tenarium ../tenarium --no-builtins --with ...
//
// It generates a throwaway main module that blank-imports the requested
// plugins next to the built-in ones and runs `go build`.
package main

import (
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

const tenariumModule = "github.com/AimTune/tenarium"

type plugin struct {
	module  string // import path
	version string // module version, if any
	replace string // local directory, if any
}

type listFlag []string

func (l *listFlag) String() string     { return strings.Join(*l, ",") }
func (l *listFlag) Set(v string) error { *l = append(*l, v); return nil }

func main() {
	var (
		with       listFlag
		output     = flag.String("o", "tenarium", "output binary path")
		tenarium   = flag.String("tenarium", "latest", "Tenarium version, or a local directory to build against")
		noBuiltins = flag.Bool("no-builtins", false, "do not include the built-in plugins")
		version    = flag.String("version", "custom", "version string embedded in the binary")
		keep       = flag.Bool("keep", false, "keep the generated build directory")
	)
	flag.Var(&with, "with", "plugin module to include: path[@version] or path=localdir (repeatable)")
	flag.Parse()

	plugins, err := parsePlugins(with)
	if err == nil {
		err = build(plugins, *output, *tenarium, *version, !*noBuiltins, *keep)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "tenarium-build:", err)
		os.Exit(1)
	}
}

func parsePlugins(specs []string) ([]plugin, error) {
	var out []plugin
	for _, s := range specs {
		p := plugin{}
		if mod, dir, ok := strings.Cut(s, "="); ok {
			abs, err := filepath.Abs(dir)
			if err != nil {
				return nil, err
			}
			p.module, p.replace = mod, abs
		} else if mod, ver, ok := strings.Cut(s, "@"); ok {
			p.module, p.version = mod, ver
		} else {
			p.module, p.version = s, "latest"
		}
		if p.module == "" {
			return nil, fmt.Errorf("invalid --with %q", s)
		}
		out = append(out, p)
	}
	return out, nil
}

func mainSource(plugins []plugin, builtins bool) string {
	var b strings.Builder
	b.WriteString("// Code generated by tenarium-build. DO NOT EDIT.\npackage main\n\nimport (\n")
	b.WriteString("\t\"" + tenariumModule + "/pkg/server\"\n")
	if builtins {
		b.WriteString("\t_ \"" + tenariumModule + "/plugins/all\"\n")
	}
	for _, p := range plugins {
		b.WriteString("\t_ \"" + p.module + "\"\n")
	}
	b.WriteString(")\n\nfunc main() { server.Main() }\n")
	return b.String()
}

func build(plugins []plugin, output, tenarium, version string, builtins, keep bool) error {
	dir, err := os.MkdirTemp("", "tenarium-build-*")
	if err != nil {
		return err
	}
	if keep {
		fmt.Fprintln(os.Stderr, "build directory:", dir)
	} else {
		defer os.RemoveAll(dir)
	}
	out, err := filepath.Abs(output)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, "main.go"), []byte(mainSource(plugins, builtins)), 0o600); err != nil {
		return err
	}

	run := func(args ...string) error {
		cmd := exec.Command("go", args...)
		cmd.Dir, cmd.Stdout, cmd.Stderr = dir, os.Stderr, os.Stderr
		fmt.Fprintln(os.Stderr, "+ go", strings.Join(args, " "))
		return cmd.Run()
	}
	if err := run("mod", "init", "tenarium-custom"); err != nil {
		return err
	}

	// A local Tenarium checkout is used through a replace directive.
	if info, err := os.Stat(tenarium); err == nil && info.IsDir() {
		abs, err := filepath.Abs(tenarium)
		if err != nil {
			return err
		}
		if err := run("mod", "edit", "-replace", tenariumModule+"="+abs, "-require", tenariumModule+"@v0.0.0"); err != nil {
			return err
		}
	} else if err := run("get", tenariumModule+"@"+tenarium); err != nil {
		return err
	}

	for _, p := range plugins {
		if p.replace != "" {
			mod, err := moduleOf(p.replace)
			if err != nil {
				return err
			}
			if err := run("mod", "edit", "-replace", mod+"="+p.replace, "-require", mod+"@v0.0.0"); err != nil {
				return err
			}
			continue
		}
		if err := run("get", p.module+"@"+p.version); err != nil {
			return err
		}
	}
	if err := run("mod", "tidy"); err != nil {
		return err
	}
	ldflags := "-s -w -X " + tenariumModule + "/pkg/server.Version=" + version
	if err := run("build", "-trimpath", "-ldflags", ldflags, "-o", out, "."); err != nil {
		return err
	}
	fmt.Fprintln(os.Stderr, "built", out)
	return nil
}

// moduleOf reads the module path from dir/go.mod.
func moduleOf(dir string) (string, error) {
	b, err := os.ReadFile(filepath.Join(dir, "go.mod"))
	if err != nil {
		return "", fmt.Errorf("local plugin %s: %w", dir, err)
	}
	for _, line := range strings.Split(string(b), "\n") {
		if mod, ok := strings.CutPrefix(strings.TrimSpace(line), "module "); ok {
			return strings.Trim(strings.TrimSpace(mod), `"`), nil
		}
	}
	return "", fmt.Errorf("no module directive in %s/go.mod", dir)
}
