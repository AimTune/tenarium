// Global setup: starts the fake OpenID provider and DNS (fakes/idp.ts), builds
// Tenarium (./tests/ui/testserver: cmd/tenarium whose domain verification asks the
// fake DNS), starts it on a free port with the in-memory store and a seeded platform
// admin, and stops both after the run. The server's URL and log file reach the tests
// through TENARIUM_URL and TENARIUM_LOG, the fake's address through FAKE_IDP_URL.
import { execFileSync, spawn } from "node:child_process";
import fs from "node:fs";
import net from "node:net";
import path from "node:path";

import { CLIENT_SECRET, startFakeIdP } from "./fakes/idp";
import { ADMIN_EMAIL, ADMIN_PASSWORD } from "./tests/env";

const repo = path.resolve(__dirname, "../..");
const work = path.join(__dirname, ".server");

function freePort(): Promise<number> {
  return new Promise((resolve, reject) => {
    const srv = net.createServer();
    srv.unref();
    srv.on("error", reject);
    srv.listen(0, "127.0.0.1", () => {
      const { port } = srv.address() as net.AddressInfo;
      srv.close(() => resolve(port));
    });
  });
}

function config(port: number, idp: string): string {
  return `# Generated by tests/ui/global-setup.ts
server:
  addr: "127.0.0.1:${port}"
log:
  level: info
  format: json
store:
  driver: memory
events:
  poll_interval: 200ms
tenants:
  require_known_plans: true
  member_roles: [owner, admin, member, viewer]
  regions: [eu, us]
  default_region: eu
bootstrap:
  plans:
    - id: free
      name: Free
      features: {sso: false, audit_log: false}
      limits: {members: 5, api_calls: 10000}
    - id: pro
      name: Pro
      features: {sso: true, audit_log: true}
      limits: {members: 100, api_calls: 1000000}
  users:
    - email: ${ADMIN_EMAIL}
      name: UI Test Admin
      roles: [admin]
      password: "${ADMIN_PASSWORD}"
users:
  # A domain name, not an IP: passkeys are bound to this host (and localhost is a
  # secure context for Chromium even over http).
  public_url: http://localhost:${port}
  password_min_length: 12
  magic_link_ttl: 15m
auth:
  tokens: {enabled: true}
  rate_limit: 0          # every test signs in through the form
  webauthn: {enabled: true}
  sso:
    enabled: true
    allow_private_issuers: true   # the fake provider runs on 127.0.0.1 over http
  social:
    allow_private_issuers: true
    providers:
      - name: fakeid
        type: oidc
        label: FakeID
        issuer: ${idp}/social
        client_id: tenarium-ui-social
        client_secret: ${CLIENT_SECRET}
        auto_create: true
ui:
  enabled: true
`;
}

async function waitReady(url: string, server: { exited: boolean }, log: string) {
  const deadline = Date.now() + 60_000;
  while (Date.now() < deadline) {
    if (server.exited) throw new Error(`tenarium exited during startup:\n${fs.readFileSync(log, "utf8")}`);
    try {
      if ((await fetch(`${url}/readyz`)).ok) return;
    } catch { /* not listening yet */ }
    await new Promise((r) => setTimeout(r, 200));
  }
  throw new Error(`tenarium did not become ready:\n${fs.readFileSync(log, "utf8")}`);
}

export default async function globalSetup() {
  fs.mkdirSync(work, { recursive: true });
  let bin = process.env.TENARIUM_BIN;
  if (!bin) {
    bin = path.join(work, process.platform === "win32" ? "tenarium.exe" : "tenarium");
    execFileSync("go", ["build", "-o", bin, "./tests/ui/testserver"], { cwd: repo, stdio: "inherit" });
  }
  const idp = await startFakeIdP();
  const port = await freePort();
  const cfg = path.join(work, "config.yaml");
  const log = path.join(work, "server.log");
  fs.writeFileSync(cfg, config(port, idp.url));
  const out = fs.openSync(log, "w");
  const child = spawn(bin, ["-config", cfg], {
    cwd: work, stdio: ["ignore", out, out], env: { ...process.env, TENARIUM_UI_TEST_DNS: `${idp.url}/dns/txt` },
  });
  const state = { exited: false };
  child.on("exit", () => (state.exited = true));

  // The API is reached on the IPv4 address; the browser uses localhost, the
  // origin users.public_url (and so the passkey relying party) names.
  await waitReady(`http://127.0.0.1:${port}`, state, log);
  process.env.TENARIUM_URL = `http://localhost:${port}`;
  process.env.TENARIUM_LOG = log;
  process.env.FAKE_IDP_URL = idp.url;

  return async () => {
    if (!state.exited) {
      child.kill();
      await new Promise((r) => child.once("exit", r));
    }
    fs.closeSync(out);
    await idp.close();
  };
}
