// The language is the saved choice, else the browser's first supported one, else English.
const langStore = {
  get() {
    try { return localStorage.getItem("tenarium.lang") || ""; } catch { return ""; }
  },
  set(v) {
    try { localStorage.setItem("tenarium.lang", v); } catch { /* storage may be blocked */ }
  },
};
const supported = (code) => (code && messages[code] ? code : "");
let lang = supported(langStore.get())
  || (navigator.languages || [navigator.language]).map((l) => supported(String(l || "").slice(0, 2).toLowerCase())).find(Boolean)
  || "en";

function setLanguage(code) {
  lang = supported(code) || "en";
  langStore.set(lang);
}

// t translates a message key and fills {placeholders} from vars.
function t(key, vars) {
  const s = messages[lang]?.[key] || key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}
