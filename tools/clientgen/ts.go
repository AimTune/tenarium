const generatedHeader = "Code generated by tools/clientgen from internal/api/openapi.yaml. DO NOT EDIT."

// tsReserved are words that cannot be parameter names in TypeScript, plus
// the names the generated methods use for their own parameters.
var tsReserved = map[string]bool{
	"break": true, "case": true, "catch": true, "class": true, "const": true, "continue": true,
	"debugger": true, "default": true, "delete": true, "do": true, "else": true, "enum": true,
	"export": true, "extends": true, "false": true, "finally": true, "for": true, "function": true,
	"if": true, "import": true, "in": true, "instanceof": true, "new": true, "null": true,
	"return": true, "super": true, "switch": true, "this": true, "throw": true, "true": true,
	"try": true, "typeof": true, "var": true, "void": true, "while": true, "with": true,
	"yield": true, "let": true, "static": true, "implements": true, "interface": true,
	"package": true, "private": true, "protected": true, "public": true, "await": true,
	"arguments": true, "eval": true,
	"query": true, "body": true, "options": true, "cursor": true,
}

type tsGen struct {
	m    *model
	used map[string]bool // named types referenced while rendering
}

// genTypeScript renders src/generated/types.ts and src/generated/operations.ts.
func genTypeScript(m *model) (types, operations []byte, err error) {
	g := &tsGen{m: m, used: map[string]bool{}}
	types, err = g.types()
	if err != nil {
		return nil, nil, err
	}
	operations, err = g.operations()
	return types, operations, err
}

func (g *tsGen) types() ([]byte, error) {
	var b strings.Builder
	b.WriteString("// " + generatedHeader + "\n")
	b.WriteString("//\n// Types of the Tenarium REST API: the schemas of the spec, named types for\n")
	b.WriteString("// inline request and response bodies, and the query parameters of each operation.\n")
	b.WriteString("// int64 values are plain numbers, exact up to Number.MAX_SAFE_INTEGER.\n")

	for _, name := range sortedKeys(g.m.schemas) {
		s := g.m.schemas[name]
		b.WriteString("\n")
		g.declare(&b, name, s)
	}

	for _, o := range g.m.ops {
		if len(o.QueryParams) == 0 {
			continue
		}
		name := pascal(o.ID) + "Query"
		if _, taken := g.m.schemas[name]; taken {
			return nil, fmt.Errorf("query type %s collides with a schema", name)
		}
		b.WriteString("\n")
		tsDoc(&b, "", []string{"Query parameters of `" + o.ID + "`."}, false)
		b.WriteString("export interface " + name + " {\n")
		for _, p := range o.QueryParams {
			tsDoc(&b, "  ", descLines(p.Description), false)
			opt := "?"
			if p.Required {
				opt = ""
			}
			b.WriteString("  " + tsKey(p.Name) + opt + ": " + g.paramType(p.Schema) + ";\n")
		}
		b.WriteString("}\n")
	}
	return []byte(b.String()), nil
}

// declare renders a named type: an interface for record schemas, an
// alias for everything else.
func (g *tsGen) declare(b *strings.Builder, name string, s *schema) {
	tsDoc(b, "", descLines(s.Description), s.Deprecated)
	if !hasProps(s) {
		b.WriteString("export type " + name + " = " + g.typ(s) + ";\n")
		return
	}
	var bases []string
	props, required := mergeRecord(s)
	for _, a := range s.AllOf {
		if a.Ref != "" {
			bases = append(bases, g.typ(a))
		}
	}
	b.WriteString("export interface " + name)
	if len(bases) > 0 {
		b.WriteString(" extends " + strings.Join(bases, ", "))
	}
	b.WriteString(" {\n")
	for _, p := range props {
		tsDoc(b, "  ", descLines(p.Schema.Description), p.Schema.Deprecated)
		opt := "?"
		if required[p.Name] {
			opt = ""
		}
		b.WriteString("  " + tsKey(p.Name) + opt + ": " + g.typ(p.Schema) + ";\n")
	}
	if s.AdditionalProperties != nil && s.AdditionalProperties.Schema != nil {
		b.WriteString("  [key: string]: unknown;\n")
	}
	b.WriteString("}\n")
}

// mergeRecord returns the own properties of a record schema: its
// properties plus those of inline allOf members, and which are required.
func mergeRecord(s *schema) (properties, map[string]bool) {
	var props properties
	required := map[string]bool{}
	pos := map[string]int{}
	add := func(x *schema) {
		for _, p := range x.Properties {
			if i, ok := pos[p.Name]; ok {
				props[i] = p
				continue
			}
			pos[p.Name] = len(props)
			props = append(props, p)
		}
		for _, r := range x.Required {
			required[r] = true
		}
	}
	add(s)
	for _, a := range s.AllOf {
		if a.Ref == "" {
			add(a)
		}
	}
	return props, required
}

// typ renders a schema as a TypeScript type expression.
func (g *tsGen) typ(s *schema) string {
	if s == nil {
		return "unknown"
	}
	if s.Ref != "" {
		name := strings.TrimPrefix(s.Ref, schemaRef)
		g.used[name] = true
		return withNull(name, s.Nullable)
	}
	nullable := s.Nullable || s.Type.has("null")
	switch {
	case s.Const != nil:
		return withNull(tsLiteral(s.Const), nullable)
	case len(s.Enum) > 0:
		var lits []string
		for _, v := range s.Enum {
			if v == nil {
				nullable = true
				continue
			}
			lits = append(lits, tsLiteral(v))
		}
		return withNull(strings.Join(lits, " | "), nullable)
	case len(s.OneOf) > 0 || len(s.AnyOf) > 0:
		var parts []string
		for _, x := range append(append([]*schema{}, s.OneOf...), s.AnyOf...) {
			parts = append(parts, paren(g.typ(x)))
		}
		return withNull(strings.Join(parts, " | "), nullable)
	case len(s.AllOf) > 0:
		var parts []string
		for _, x := range s.AllOf {
			parts = append(parts, paren(g.typ(x)))
		}
		if len(s.Properties) > 0 {
			parts = append(parts, g.inlineObject(s))
		}
		return withNull(strings.Join(parts, " & "), nullable)
	}
	var parts []string
	for _, t := range s.Type.nonNull() {
		parts = append(parts, g.primitive(t, s))
	}
	if len(parts) == 0 {
		switch {
		case len(s.Properties) > 0 || s.AdditionalProperties != nil:
			parts = append(parts, g.primitive("object", s))
		case s.Items != nil:
			parts = append(parts, g.primitive("array", s))
		default:
			parts = append(parts, "unknown")
		}
	}
	return withNull(strings.Join(parts, " | "), nullable)
}

func (g *tsGen) primitive(t string, s *schema) string {
	switch t {
	case "string":
		return "string"
	case "integer", "number":
		return "number"
	case "boolean":
		return "boolean"
	case "array":
		return paren(g.typ(s.Items)) + "[]"
	case "object":
		if len(s.Properties) > 0 {
			return g.inlineObject(s)
		}
		if ap := s.AdditionalProperties; ap != nil {
			if ap.Schema != nil {
				return "Record<string, " + g.typ(ap.Schema) + ">"
			}
			if ap.Allowed != nil && !*ap.Allowed {
				return "Record<string, never>"
			}
		}
		return "Record<string, unknown>"
	}
	return "unknown"
}

// inlineObject renders properties as an object literal type. Hoisting
// leaves these only inside allOf expressions.
func (g *tsGen) inlineObject(s *schema) string {
	req := map[string]bool{}
	for _, r := range s.Required {
		req[r] = true
	}
	var fields []string
	for _, p := range s.Properties {
		opt := "?"
		if req[p.Name] {
			opt = ""
		}
		fields = append(fields, tsKey(p.Name)+opt+": "+g.typ(p.Schema))
	}
	return "{ " + strings.Join(fields, "; ") + " }"
}

// paramType is the type of a path or query parameter. int64 parameters
// also accept strings, since cursors such as event sequence numbers can
// exceed the safe integer range and come back as strings in `next`.
func (g *tsGen) paramType(s *schema) string {
	t := g.typ(s)
	if s != nil && s.Ref == "" && s.Type.has("integer") && s.Format == "int64" {
		return t + " | string"
	}
	return t
}

func (g *tsGen) operations() ([]byte, error) {
	g.used = map[string]bool{}
	var body strings.Builder
	ids := map[string]bool{}
	for _, o := range g.m.ops {
		ids[o.ID] = true
	}
	for _, o := range g.m.ops {
		if err := g.method(&body, o, ids); err != nil {
			return nil, fmt.Errorf("%s: %w", o.ID, err)
		}
	}

	var b strings.Builder
	b.WriteString("// " + generatedHeader + "\n\n")
	b.WriteString("import type { OperationRequest, Page, RequestOptions } from \"../request.ts\";\n")
	var names []string
	for n := range g.used {
		names = append(names, n)
	}
	sort.Strings(names)
	if len(names) > 0 {
		b.WriteString("import type {\n")
		for _, n := range names {
			b.WriteString("  " + n + ",\n")
		}
		b.WriteString("} from \"./types.ts\";\n")
	}
	b.WriteString("\n/**\n * One method per operation of the Tenarium API, named after its operationId.\n")
	b.WriteString(" * {@link Client} extends this class and supplies the transport.\n */\n")
	b.WriteString("export abstract class Operations {\n")
	b.WriteString("  /** Sends one API request and returns the decoded JSON body. */\n")
	b.WriteString("  protected abstract request<T>(req: OperationRequest): Promise<T>;\n\n")
	b.WriteString("  /** Yields the items of successive pages until `next` is absent. */\n")
	b.WriteString("  protected abstract paginate<T>(fetch: (cursor: string | undefined) => Promise<Page<T>>): AsyncIterableIterator<T>;\n")
	b.WriteString(body.String())
	b.WriteString("}\n")
	return []byte(b.String()), nil
}

func (g *tsGen) method(b *strings.Builder, o *op, ids map[string]bool) error {
	type arg struct{ decl, name string }
	var args []arg
	var pathArgs []string
	taken := map[string]bool{}
	for _, p := range o.PathParams {
		v := tsVar(p.Name, taken)
		args = append(args, arg{v + ": " + g.paramType(p.Schema), v})
		if v == p.Name {
			pathArgs = append(pathArgs, v)
		} else {
			pathArgs = append(pathArgs, tsKey(p.Name)+": "+v)
		}
	}
	queryRequired := false
	for _, p := range o.QueryParams {
		queryRequired = queryRequired || p.Required
	}
	if o.Body != nil {
		t := g.typ(o.Body)
		switch {
		case o.BodyRequired:
			args = append(args, arg{"body: " + t, "body"})
		case queryRequired:
			args = append(args, arg{"body: " + t + " | undefined", "body"})
		default:
			args = append(args, arg{"body?: " + t, "body"})
		}
	}
	queryType := pascal(o.ID) + "Query"
	if len(o.QueryParams) > 0 {
		g.used[queryType] = true
		if queryRequired {
			args = append(args, arg{"query: " + queryType, "query"})
		} else {
			args = append(args, arg{"query: " + queryType + " = {}", "query"})
		}
	}
	args = append(args, arg{"options: RequestOptions = {}", "options"})

	result := "unknown"
	switch {
	case o.Result != nil:
		result = g.typ(o.Result)
	case o.Status == "204":
		result = "void"
	}

	var doc []string
	if o.Summary != "" {
		doc = append(doc, strings.TrimSuffix(o.Summary, ".")+".")
	}
	if o.Description != "" {
		doc = appendParagraph(doc, paragraphs(o.Description)...)
	}
	doc = appendParagraph(doc, "`"+o.Method+" "+o.Path+"`")
	for _, p := range o.PathParams {
		if p.Description != "" {
			doc = append(doc, "@param "+tsVarName(p.Name)+" "+oneLine(p.Description))
		}
	}
	b.WriteString("\n")
	tsDoc(b, "  ", doc, o.Deprecated)

	decls := make([]string, len(args))
	for i, a := range args {
		decls[i] = a.decl
	}
	fmt.Fprintf(b, "  %s(%s): Promise<%s> {\n", o.ID, strings.Join(decls, ", "), result)
	fields := []string{"method: " + jsString(o.Method), "path: " + jsString(o.Path)}
	if len(pathArgs) > 0 {
		fields = append(fields, "pathParams: { "+strings.Join(pathArgs, ", ")+" }")
	}
	if len(o.QueryParams) > 0 {
		fields = append(fields, "query")
	}
	if o.Body != nil {
		fields = append(fields, "body", "contentType: "+jsString(o.BodyContentType))
	}
	if o.Public {
		fields = append(fields, "public: true")
	}
	if o.AutoIdem {
		fields = append(fields, "autoIdempotencyKey: true")
	}
	fields = append(fields, "options")
	fmt.Fprintf(b, "    return this.request<%s>({ %s });\n  }\n", result, strings.Join(fields, ", "))

	if o.Paging == nil {
		return nil
	}
	name := o.ID + "All"
	if ids[name] {
		return fmt.Errorf("iterator name %s collides with an operation", name)
	}
	item := g.typ(o.Paging.Item)
	var callArgs []string
	var iterDecls []string
	for _, a := range args {
		iterDecls = append(iterDecls, a.decl)
		if a.name == "query" {
			callArgs = append(callArgs, "cursor === undefined ? query : { ...query, "+tsKey(o.Paging.Cursor)+": cursor }")
		} else {
			callArgs = append(callArgs, a.name)
		}
	}
	b.WriteString("\n")
	tsDoc(b, "  ", []string{
		"Iterates over every item of {@link Operations." + o.ID + "}, fetching pages as needed",
		"(`next` is sent back as `" + o.Paging.Cursor + "`).",
	}, o.Deprecated)
	fmt.Fprintf(b, "  %s(%s): AsyncIterableIterator<%s> {\n", name, strings.Join(iterDecls, ", "), item)
	fmt.Fprintf(b, "    return this.paginate<%s>((cursor) => this.%s(%s));\n  }\n", item, o.ID, strings.Join(callArgs, ", "))
	return nil
}

// --- helpers ------------------------------------------------------------------------

func tsVarName(name string) string {
	v := camel(name)
	if !isIdent(v) || tsReserved[v] {
		v += "_"
	}
	return v
}

func tsVar(name string, taken map[string]bool) string {
	v := tsVarName(name)
	for taken[v] {
		v += "_"
	}
	taken[v] = true
	return v
}

func tsKey(name string) string {
	if isIdent(name) {
		return name
	}
	return jsString(name)
}

func jsString(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

func tsLiteral(v any) string {
	b, err := json.Marshal(v)
	if err != nil {
		return "unknown"
	}
	return string(b)
}

func withNull(t string, nullable bool) string {
	if nullable && t != "unknown" {
		return t + " | null"
	}
	return t
}

// paren wraps unions and intersections so they can be combined.
func paren(t string) string {
	if strings.ContainsAny(t, "|&") && !strings.HasPrefix(t, "{") && !strings.HasPrefix(t, "Record<") {
		return "(" + t + ")"
	}
	return t
}

func descLines(desc string) []string {
	if strings.TrimSpace(desc) == "" {
		return nil
	}
	return paragraphs(desc)
}

func tsDoc(b *strings.Builder, indent string, lines []string, deprecated bool) {
	if deprecated {
		lines = append(lines, "@deprecated")
	}
	if len(lines) == 0 {
		return
	}
	esc := func(s string) string { return strings.ReplaceAll(s, "*/", "*\\/") }
	if len(lines) == 1 {
		b.WriteString(indent + "/** " + esc(lines[0]) + " */\n")
		return
	}
	b.WriteString(indent + "/**\n")
	for _, l := range lines {
		if l == "" {
			b.WriteString(indent + " *\n")
		} else {
			b.WriteString(indent + " * " + esc(l) + "\n")
		}
	}
	b.WriteString(indent + " */\n")
}
